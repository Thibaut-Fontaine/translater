#!/usr/bin/env python3
"""Generate docs/language-matrix.md from the three upstream sources.

    python3 scripts/gen_language_matrix.py

Network access is required (it is a documentation tool, not part of the build).
Matching is by English language name with a small alias table; entries that
appear in only one source are still listed, which is the point of the table.
"""
import json
import re
import sys
import urllib.request

UA = {"User-Agent": "Mozilla/5.0 xtrans-language-matrix"}
WHISPER_URL = "https://whisper-api.com/docs/languages/"
PIPER_URL = "https://huggingface.co/rhasspy/piper-voices/resolve/main/voices.json"
FLORES_URL = "https://raw.githubusercontent.com/facebookresearch/flores/main/flores200/README.md"

ALIASES = {
    "myanmar": "burmese",
    "farsi": "persian",
    "western persian": "persian",
    "standard tibetan": "tibetan",
    "standard malay": "malay",
    "haitian": "haitian creole",
    "filipino": "tagalog",
    "castilian": "spanish",
    "modern standard arabic": "arabic",
}


def fetch(url):
    req = urllib.request.Request(url, headers=UA)
    with urllib.request.urlopen(req, timeout=60) as r:
        return r.read().decode("utf-8", "replace")


def key(name):
    name = re.sub(r"\([^)]*\)", "", name).strip().lower()
    return ALIASES.get(name, name)


def whisper_languages():
    lines = [l.strip() for l in re.sub(r"<[^>]+>", "\n", fetch(WHISPER_URL)).split("\n") if l.strip()]
    out = {}
    for i in range(len(lines) - 1):
        if re.fullmatch(r"[a-z]{2,3}", lines[i]) and re.fullmatch(r"[A-Z][A-Za-z ()\-]+", lines[i + 1]):
            out[key(lines[i + 1])] = lines[i]
    return out


def piper_voices():
    data = json.loads(fetch(PIPER_URL))
    out = {}
    for voice, meta in data.items():
        lang = meta.get("language", {})
        name = lang.get("name_english") or lang.get("code", "")
        locale = lang.get("code", "")
        entry = out.setdefault(key(name), {"count": 0, "locales": set()})
        entry["count"] += 1
        entry["locales"].add(locale)
    return out


def nllb_languages():
    out = {}
    for line in fetch(FLORES_URL).splitlines():
        m = re.match(r"^(.+?)\s*\|\s*([a-z]{3}_[A-Za-z]{4})\s*$", line.strip())
        if m:
            out.setdefault(key(m.group(1)), []).append(m.group(2))
    return out


def main():
    whisper = whisper_languages()
    piper = piper_voices()
    nllb = nllb_languages()

    names = sorted(set(whisper) | set(piper) | set(nllb))
    rows = []
    dropped = 0
    for name in names:
        w = whisper.get(name)
        p = piper.get(name)
        n = nllb.get(name)
        if not w and not p and not n:  # absent everywhere: never listed
            dropped += 1
            continue
        display = name[:1].upper() + name[1:]
        w_cell = f"`{w}`" if w else "—"
        n_cell = ", ".join(f"`{c}`" for c in n) if n else "—"
        if p:
            locale = ", ".join(sorted(p["locales"])[:2])
            p_cell = f"{p['count']} · {locale}"
        else:
            p_cell = "—"
        rows.append(f"| {display} | {w_cell} | {n_cell} | {p_cell} |")

    lines = [
        "# Language matrix: Whisper vs NLLB-200 vs Piper",
        "",
        "Generated by `scripts/gen_language_matrix.py`. Sources:",
        "",
        f"- Whisper: <{WHISPER_URL}> — {len(whisper)} languages",
        f"- NLLB-200: <{FLORES_URL}> — 200 languages, "
        f"{sum(len(v) for v in nllb.values())} codes (some languages have two scripts)",
        f"- Piper: <{PIPER_URL}> — {sum(v['count'] for v in piper.values())} voices "
        f"across {len(piper)} languages",
        "",
        "A language is usable end to end only when all three columns are filled.",
        "Rows are languages that appear in **at least one** source; a dash means the",
        "component has no support for it. Matching is by English name with a small",
        "alias table (`Myanmar` → Burmese, `Farsi` → Persian, `Standard Tibetan` →",
        "Tibetan, …), so an occasional mis-merge is possible — the upstream sources",
        "remain authoritative.",
        "",
        f"{len(rows)} languages listed.",
        "",
        "| Language | Whisper code | NLLB-200 code | Piper voices |",
        "| --- | --- | --- | --- |",
    ]
    lines.extend(rows)
    lines.append("")

    path = "docs/language-matrix.md"
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print(f"wrote {path}: {len(rows)} rows, {dropped} dropped (absent everywhere)")
    return 0


if __name__ == "__main__":
    sys.exit(main())

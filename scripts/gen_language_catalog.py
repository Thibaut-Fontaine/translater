#!/usr/bin/env python3
"""Generate the language catalog from the matrix and the NLLB tokenizer.

    python3 scripts/gen_language_catalog.py [--tokenizer PATH] [--json PATH]

Inputs
  docs/language-matrix.md          committed, generated by gen_language_matrix.py
  models/nllb/tokenizer.json       downloaded by fetch_models.sh (needed for ids)

Outputs (all committed, so the build stays offline)
  include/xtrans/lang_generated.inc   enum Lang enumerators
  src/lang_table_generated.inc        LangInfo rows + per-mode selections
  mobile/src/data/catalog.json      the app's language list

Why generate
  NLLB-200 has 205 language codes and their token ids live in the tokenizer's
  added tokens. Transcribing them by hand is how the five-language table came to
  exist; the phone app needs the whole set. The script is deterministic: same
  matrix + same tokenizer => same files, byte for byte.
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

# The five historical languages keep their enum values (stored in config files
# on the Pi) and their validated capability bits.
LEGACY = {
    "fra_Latn": dict(
        enum="fr", iso="fra", nllb="fra_Latn", whisper="fr",
        piper="fr_FR-siwis-medium", caps="kReady", name="French",
    ),
    "eng_Latn": dict(
        enum="en", iso="eng", nllb="eng_Latn", whisper="en",
        piper="en_US-lessac-medium", caps="kReady", name="English",
    ),
    "tha_Thai": dict(
        enum="th", iso="tha", nllb="tha_Thai", whisper="th",
        piper="", caps="kStt | kMt", name="Thai",
    ),
    "lao_Laoo": dict(
        enum="lo", iso="lao", nllb="lao_Laoo", whisper="lo",
        piper="", caps="kStt | kMt", name="Lao",
    ),
}
LEGACY_ORDER = ["fr", "en", "th", "lo", "hmn"]
LEGACY_EXTRA = dict(
    enum="hmn", iso="hmn", nllb="", whisper="", piper="", caps="0", name="Hmong",
)

CXX_KEYWORDS = {
    "alignas", "alignof", "and", "and_eq", "asm", "auto", "bitand", "bitor",
    "bool", "break", "case", "catch", "char", "char8_t", "char16_t", "char32_t",
    "class", "compl", "concept", "const", "consteval", "constexpr", "constinit",
    "const_cast", "continue", "co_await", "co_return", "co_yield", "decltype",
    "default", "delete", "do", "double", "dynamic_cast", "else", "enum",
    "explicit", "export", "extern", "false", "float", "for", "friend", "goto",
    "if", "inline", "int", "long", "mutable", "namespace", "new", "noexcept",
    "not", "not_eq", "nullptr", "operator", "or", "or_eq", "private",
    "protected", "public", "register", "reinterpret_cast", "requires", "return",
    "short", "signed", "sizeof", "static", "static_assert", "static_cast",
    "struct", "switch", "template", "this", "thread_local", "throw", "true",
    "try", "typedef", "typeid", "typename", "union", "unsigned", "using",
    "virtual", "void", "volatile", "wchar_t", "while", "xor", "xor_eq",
}


def parse_matrix(path: Path):
    """Return [{name, whisper, codes: [..]}] in file order."""
    rows = []
    for line in path.read_text(encoding="utf-8").splitlines():
        if not line.startswith("| "):
            continue
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) < 4 or cells[0] in ("Language", "---"):
            continue
        if cells[0].startswith("---"):
            continue
        name = cells[0]
        found = [re.findall(r"`([^`]+)`", c) for c in cells[1:4]]
        whisper_codes, nllb_codes, piper_voices = found
        if not nllb_codes:
            continue
        rows.append(dict(
            name=name,
            whisper=whisper_codes[0] if whisper_codes else "",
            codes=nllb_codes,
            has_piper=bool(piper_voices) or "·" in cells[3],
        ))
    return rows


def token_ids(path: Path):
    data = json.loads(path.read_text(encoding="utf-8"))
    return {t["content"]: t["id"] for t in data.get("added_tokens", [])}


def script_label(code: str) -> str:
    return code.split("_", 1)[1] if "_" in code else ""


def cxx(value: str) -> str:
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def build(rows, ids):
    entries = []
    for row in rows:
        multi = len(row["codes"]) > 1
        for code in row["codes"]:
            if code in LEGACY:
                continue
            lang_id = ids.get(code)
            if lang_id is None:
                continue
            enum = code
            if enum in CXX_KEYWORDS or not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", enum):
                enum = "lang_" + enum
            name = row["name"]
            if multi:
                label = script_label(code)
                name = f"{name} ({label})" if label else name
            caps = "kMt" + (" | kStt" if row["whisper"] else "")
            entries.append(dict(
                enum=enum, iso=code.split("_")[0], nllb=code, whisper=row["whisper"],
                piper="", caps=caps, name=name, id=lang_id,
            ))

    entries.sort(key=lambda e: e["enum"])
    seen = set()
    for e in entries:
        if e["enum"] in seen:
            raise SystemExit(f"duplicate enumerator {e['enum']}")
        seen.add(e["enum"])

    legacy = []
    for enum in LEGACY_ORDER:
        if enum == "hmn":
            e = dict(LEGACY_EXTRA, id=0)
        else:
            code = next(k for k, v in LEGACY.items() if v["enum"] == enum)
            e = dict(LEGACY[code], id=ids.get(code, 0))
        legacy.append(e)
    return legacy, entries


def emit_enum(legacy, entries):
    lines = [
        "// Generated by scripts/gen_language_catalog.py. Do not edit.",
        "// NLLB-200 language codes, appended after the historical five so stored",
        "// values keep their meaning. The legacy five are declared in language.hpp.",
    ]
    lines += [f"  {e['enum']}," for e in entries]
    return "\n".join(lines) + "\n"


def emit_table(legacy, entries):
    all_entries = legacy + entries
    lines = [
        "// Generated by scripts/gen_language_catalog.py. Do not edit.",
        "constexpr std::array<LangInfo, kLangCount> kTable{{",
    ]
    for e in all_entries:
        lines.append(
            "    {Lang::%s, %s, %s, %s, %s, %s, %d, %s},"
            % (e["enum"], cxx(e["name"]), cxx(e["iso"]), cxx(e["nllb"]),
               cxx(e["whisper"]), cxx(e["piper"]), e["id"], e["caps"])
        )
    lines.append("}};")
    lines.append("")

    def caps_of(e):
        caps = e["caps"]
        if caps == "kReady":
            return {"kStt", "kMt", "kTts"}
        return {bit for bit in ("kStt", "kMt", "kTts") if bit in caps}

    def ids_of(*required):
        return [e["enum"] for e in all_entries if set(required) <= caps_of(e)]

    groups = {
        "kSpeechToSpeech": ids_of("kStt", "kMt", "kTts"),
        "kSpeechToText": ids_of("kStt", "kMt"),
        "kTextToText": ids_of("kMt"),
        "kTextToSpeech": ids_of("kMt", "kTts"),
    }

    for name, langs in groups.items():
        hint = "Pi-validated (STT + MT + Piper voice)" if name in (
            "kSpeechToSpeech", "kTextToSpeech") else "text path exists"
        lines.append(f"// {hint}")
        lines.append(f"constexpr std::array<Lang, {len(langs)}> {name}{{{{")
        for i in range(0, len(langs), 4):
            lines.append("    " + " ".join(f"Lang::{n}," for n in langs[i:i + 4]))
        lines.append("}};")
        lines.append("")
    return "\n".join(lines) + "\n"


def emit_json(legacy, entries):
    items = []
    for value, e in enumerate(legacy + entries):
        caps = e["caps"]
        if caps == "kReady":
            has = {"kStt", "kMt", "kTts"}
        else:
            has = {bit for bit in ("kStt", "kMt", "kTts") if bit in caps}
        items.append(dict(
            value=value, id=e["enum"], name=e["name"], iso=e["iso"], nllb=e["nllb"],
            whisper=e["whisper"], nllb_id=e["id"],
            stt="kStt" in has, mt="kMt" in has, tts="kTts" in has,
        ))
    return json.dumps(dict(generated="scripts/gen_language_catalog.py", languages=items),
                      ensure_ascii=False, indent=1) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--tokenizer", default=str(ROOT / "models/nllb/tokenizer.json"))
    ap.add_argument("--matrix", default=str(ROOT / "docs/language-matrix.md"))
    ap.add_argument("--json", default=str(ROOT / "mobile/src/data/catalog.json"))
    args = ap.parse_args()

    tokenizer = Path(args.tokenizer)
    if not tokenizer.exists():
        print(f"missing {tokenizer}; run scripts/fetch_models.sh first", file=sys.stderr)
        return 1

    rows = parse_matrix(Path(args.matrix))
    ids = token_ids(tokenizer)
    legacy, entries = build(rows, ids)
    if not entries:
        print("no languages generated; check the matrix format", file=sys.stderr)
        return 1

    (ROOT / "include/xtrans/lang_generated.inc").write_text(emit_enum(legacy, entries))
    (ROOT / "src/lang_table_generated.inc").write_text(emit_table(legacy, entries))
    out_json = Path(args.json)
    out_json.parent.mkdir(parents=True, exist_ok=True)
    out_json.write_text(emit_json(legacy, entries))

    print(f"{len(legacy) + len(entries)} languages "
          f"({len(entries)} generated), {out_json.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
